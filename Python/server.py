#!/usr/bin/env python3
"""Serve Imperio Dorado on localhost and persist app state in SQLite."""

from __future__ import annotations

import argparse
import json
import sys
import webbrowser
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import urlsplit

from database import DATABASE_PATH, ROOT, initialize_database, load_state, save_state

MAX_REQUEST_BYTES = 20 * 1024 * 1024


class AppHandler(SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=str(ROOT), **kwargs)

    def _send_json(self, status: int, payload: dict):
        body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def _api_origin_is_local(self) -> bool:
        origin = self.headers.get("Origin")
        if not origin:
            return True
        parsed = urlsplit(origin)
        port = str(self.server.server_port)
        return parsed.scheme == "http" and parsed.netloc in {
            f"127.0.0.1:{port}", f"localhost:{port}"
        }

    def _api_request_is_local(self) -> bool:
        port = str(self.server.server_port)
        host = self.headers.get("Host", "")
        return self._api_origin_is_local() and host in {
            f"127.0.0.1:{port}", f"localhost:{port}"
        }

    def translate_path(self, path: str) -> str:
        root = ROOT.resolve()
        candidate = Path(super().translate_path(path)).resolve()
        try:
            relative = candidate.relative_to(root)
        except ValueError:
            return str(root / "__not_found__")
        # Keep private data, Python sources, and generated bytecode off the web root.
        if relative.parts and relative.parts[0].casefold() in {"data", "python", "__pycache__"}:
            return str(root / "__not_found__")
        if any(part.casefold() == "__pycache__" for part in relative.parts):
            return str(root / "__not_found__")
        if len(relative.parts) == 1 and candidate.suffix.lower() in {".json", ".db", ".sqlite", ".sqlite3"}:
            return str(root / "__not_found__")
        if candidate.suffix.lower() in {".py", ".pyc", ".db", ".sqlite", ".sqlite3"}:
            return str(root / "__not_found__")
        return str(candidate)

    def do_GET(self):
        path = urlsplit(self.path).path
        if path in {"/", "/index.html"}:
            self.send_response(302)
            self.send_header("Location", "/HTML/index.html")
            self.send_header("Content-Length", "0")
            self.end_headers()
            return
        if path == "/api/state":
            if not self._api_request_is_local():
                self._send_json(403, {"error": "La base solo acepta solicitudes de esta computadora."})
                return
            try:
                self._send_json(200, {"initialized": True, "state": load_state()})
            except Exception as error:
                self._send_json(500, {"error": f"No se pudo leer la base SQLite: {error}"})
            return
        if path.startswith("/api/"):
            self._send_json(404, {"error": "Ruta API no disponible."})
            return
        super().do_GET()

    def do_PUT(self):
        if urlsplit(self.path).path != "/api/state":
            self._send_json(404, {"error": "Ruta API no disponible."})
            return
        if not self._api_request_is_local():
            self._send_json(403, {"error": "La base solo acepta solicitudes de esta computadora."})
            return
        content_type = self.headers.get("Content-Type", "").split(";", 1)[0].strip().lower()
        if content_type != "application/json":
            self._send_json(415, {"error": "El estado debe enviarse como JSON."})
            return
        try:
            size = int(self.headers.get("Content-Length", "0"))
            if size <= 0 or size > MAX_REQUEST_BYTES:
                self._send_json(413, {"error": "El tamaño del estado no es válido."})
                return
            payload = json.loads(self.rfile.read(size).decode("utf-8"))
            if not isinstance(payload, dict):
                self._send_json(400, {"error": "El estado recibido no tiene un formato válido."})
                return
            save_state(payload)
            self._send_json(200, {"ok": True})
        except (UnicodeDecodeError, json.JSONDecodeError, ValueError) as error:
            self._send_json(400, {"error": f"No se guardaron los datos: {error}"})
        except Exception as error:
            self._send_json(500, {"error": f"No se pudo guardar en SQLite: {error}"})

    def log_message(self, format, *args):
        super().log_message(format, *args)


def main() -> int:
    parser = argparse.ArgumentParser(description="Inicia Imperio Dorado con su base SQLite local.")
    parser.add_argument("--port", type=int, default=8765, help="Puerto local (predeterminado: 8765).")
    parser.add_argument("--no-open", action="store_true", help="No abrir el navegador automáticamente.")
    args = parser.parse_args()

    try:
        created = initialize_database()
        server = ThreadingHTTPServer(("127.0.0.1", args.port), AppHandler)
    except OSError as error:
        print(f"No se pudo iniciar el servidor: {error}", file=sys.stderr)
        return 1

    address = f"http://127.0.0.1:{args.port}/"
    print("Base SQLite:", DATABASE_PATH)
    print("Datos cargados desde el respaldo incluido." if created else "Se conserva la base SQLite existente.")
    print("Aplicación local:", address)
    print("Detén el servidor con Ctrl+C.")
    if not args.no_open:
        webbrowser.open_new_tab(address)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nServidor detenido.")
    finally:
        server.server_close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
